export type TKey = keyof typeof zh
const dictionaries: Record<Locale, Record<TKey, string>> = { 'zh-CN': zh, en }

const LOCALE_KEY = 'iteam.locale'
const detect = (): Locale => {
  const saved = localStorage.getItem(LOCALE_KEY)
  if (saved === 'en' || saved === 'zh-CN') return saved
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en'
}

interface I18n {
  locale: Locale
  setLocale: (l: Locale) => void
  t: (key: TKey, vars?: Record<string, string | number>) => string
}

const I18nContext = createContext<I18n | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(detect)
  const value = useMemo<I18n>(
    () => ({
      locale,
      setLocale: (l) => {
        localStorage.setItem(LOCALE_KEY, l)
        setLocaleState(l)
      },
      t: (key, vars) => {
        let text = dictionaries[locale][key] ?? key
        if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
        return text
      },
    }),
    [locale],
  )
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useT(): I18n {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useT must be used inside I18nProvider')
  return ctx
}
