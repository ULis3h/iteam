/**
 * The built-in "demo" provider: a simulated agent that streams a few tool events and
 * writes a plausible Markdown deliverable derived from the prompt, without calling any
 * model. It exists so the product can be tried end to end before any CLI is installed.
 */

type Kind = 'plan' | 'implement' | 'review' | 'test' | 'research' | 'generic'

const hasCjk = (s: string) => /[\u4e00-\u9fff]/.test(s)

const detectKind = (text: string): Kind => {
  const p = text.toLowerCase()
  if (/(评审|审查|review|audit)/.test(p)) return 'review'
  if (/(测试|test)/.test(p)) return 'test'
  if (/(方案|设计|架构|规划|plan|design|architect)/.test(p)) return 'plan'
  if (/(实现|修复|开发|重构|implement|fix|build|refactor|add )/.test(p)) return 'implement'
  if (/(调研|研究|报告|总结|research|report|summar)/.test(p)) return 'research'
  return 'generic'
}

/** The task part of the prompt (between the role block and the "Expected output" block). */
const taskOf = (prompt: string): { title: string; body: string; upstreamChars: number } => {
  // the server joins role / prompt / expected output with blank-line separated "---" markers;
  // upstream Markdown pasted into the prompt may contain its own "---" lines, so match exactly
  const blocks = prompt.split(/\n\n---\n\n/)
  const body = (blocks.length >= 2 ? blocks[1] : blocks[0]).trim()
  const firstLine = body.split('\n').map((l) => l.trim()).find((l) => l && !/^[#>*-]/.test(l)) ?? body.slice(0, 80)
  const title = firstLine.replace(/[:：。.!！?？]\s*$/, '').slice(0, 80)
  return { title, body, upstreamChars: Math.max(0, body.length - firstLine.length) }
}

const slugOf = (title: string) => title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 24) || 'feature'

// deterministic pseudo-random delays (seeded by the job id) so demo runs look alive but reproducible
const seeded = (seed: string) => {
  let h = 2166136261
  for (const c of seed) h = Math.imul(h ^ c.charCodeAt(0), 16777619)
  return () => {
    h = Math.imul(h ^ (h >>> 15), 2246822507)
    h = Math.imul(h ^ (h >>> 13), 3266489909)
    return ((h ^= h >>> 16) >>> 0) / 4294967296
  }
}

