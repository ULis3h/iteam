export function runDemoJob(job: JobSpec, handlers: JobHandlers): JobHandle {
  const timers: NodeJS.Timeout[] = []
  let finished = false
  const done = (result: Parameters<JobHandlers['onDone']>[0]) => {
    if (finished) return
    finished = true
    for (const t of timers) clearTimeout(t)
    handlers.onDone(result)
  }
  const { title, body, upstreamChars } = taskOf(job.stdin)
  // answer in the language of the task itself, not of whatever upstream output was pasted in
  const zh = /[A-Za-z\u4e00-\u9fff]/.test(title) ? hasCjk(title) : hasCjk(body)
  const kind = detectKind(body || job.stdin)
  const rnd = seeded(job.id)
  const slug = slugOf(title)

  handlers.onLog('system', zh ? 'demo agent · 未调用任何模型，输出为本地生成' : 'demo agent · no model is called, the output is generated locally')
  let at = 200
  for (const [zhLine, enLine] of EVENTS[kind]) {
    at += 300 + Math.floor(rnd() * 600)
    const line = (zh ? zhLine : enLine).replace('{slug}', slug).replace('{title}', title.slice(0, 40))
    timers.push(setTimeout(() => handlers.onLog('event', line), at))
  }
  at += 400 + Math.floor(rnd() * 500)
  timers.push(
    setTimeout(() => {
      handlers.onLog('event', zh ? '✓ result · demo' : '✓ result · demo')
      done({ exitCode: 0, output: output(kind, title, zh, upstreamChars) })
    }, at),
  )
  return {
    cancel: () => done({ exitCode: null, output: '', error: 'cancelled', cancelled: true }),
  }
}
